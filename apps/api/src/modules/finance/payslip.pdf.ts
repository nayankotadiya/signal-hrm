import PDFDocument from 'pdfkit';

export interface PayslipData {
  organization: { name: string; legalName?: string; address?: string };
  employee: { name: string; code: string; designation?: string; department?: string; bankLast4?: string; panLast4?: string };
  period: string;
  payDate?: string;
  currency: string;
  inputs: { periodDays: number; payableDays: number; lopDays: number };
  earnings: { name: string; amount: number }[];
  deductions: { name: string; amount: number }[];
  gross: number;
  totalDeductions: number;
  net: number;
  reference: string;
}

const money = (n: number, cur: string): string => `${cur} ${n.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/** Renders a one-page payslip PDF. Standard PDF fonts only (no network access needed). */
export function renderPayslip(d: PayslipData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: `Payslip ${d.period} ${d.employee.name}`, Author: d.organization.name } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const ink = '#0F1115';
    const muted = '#5F6570';
    doc.fillColor(ink).font('Helvetica-Bold').fontSize(18).text(d.organization.legalName || d.organization.name);
    if (d.organization.address) doc.font('Helvetica').fontSize(9).fillColor(muted).text(d.organization.address);
    doc.moveDown(0.6).font('Helvetica').fontSize(12).fillColor(ink).text(`Payslip for ${d.period}`);
    doc.moveTo(48, doc.y + 6).lineTo(547, doc.y + 6).strokeColor('#DDDDE5').stroke();
    doc.moveDown(1);

    const info: [string, string][] = [
      ['Employee', d.employee.name],
      ['Employee ID', d.employee.code],
      ['Designation', d.employee.designation ?? '-'],
      ['Department', d.employee.department ?? '-'],
      ['Days payable', `${d.inputs.payableDays} of ${d.inputs.periodDays}${d.inputs.lopDays ? ` (LOP ${d.inputs.lopDays})` : ''}`],
      ['Bank account', d.employee.bankLast4 ? `ending ${d.employee.bankLast4}` : 'not on file'],
      ['PAN', d.employee.panLast4 ? `ending ${d.employee.panLast4}` : '-'],
      ['Pay date', d.payDate ?? '-'],
    ];
    const top = doc.y;
    info.forEach(([k, v], i) => {
      const x = i % 2 === 0 ? 48 : 300;
      const y = top + Math.floor(i / 2) * 18;
      doc.font('Helvetica').fontSize(9).fillColor(muted).text(k, x, y, { width: 90 });
      doc.font('Helvetica').fontSize(9).fillColor(ink).text(v, x + 92, y, { width: 150 });
    });
    doc.y = top + Math.ceil(info.length / 2) * 18 + 16;

    const tableTop = doc.y;
    const col = (title: string, rows: { name: string; amount: number }[], x: number) => {
      doc.font('Helvetica-Bold').fontSize(10).fillColor(ink).text(title, x, tableTop, { width: 230 });
      let y = tableTop + 18;
      for (const r of rows) {
        doc.font('Helvetica').fontSize(9).fillColor(ink).text(r.name, x, y, { width: 150 });
        doc.text(money(r.amount, d.currency), x + 150, y, { width: 90, align: 'right' });
        y += 16;
      }
      return y;
    };
    const yE = col('Earnings', d.earnings, 48);
    const yD = col('Deductions', d.deductions, 300);
    let y = Math.max(yE, yD) + 6;
    doc.moveTo(48, y).lineTo(547, y).strokeColor('#DDDDE5').stroke();
    y += 8;
    doc.font('Helvetica-Bold').fontSize(9).text('Gross earnings', 48, y, { width: 150 }).text(money(d.gross, d.currency), 198, y, { width: 90, align: 'right' });
    doc.text('Total deductions', 300, y, { width: 150 }).text(money(d.totalDeductions, d.currency), 450, y, { width: 90, align: 'right' });
    y += 30;
    doc.roundedRect(48, y, 499, 44, 10).fill('#F2F4F7');
    doc.fillColor(ink).font('Helvetica-Bold').fontSize(14).text(`Net pay  ${money(d.net, d.currency)}`, 64, y + 14);
    doc.font('Helvetica').fontSize(8).fillColor(muted).text(`Reference ${d.reference} · Generated by Signal HRM. This is a system-generated document.`, 48, 780, { width: 499, align: 'center' });
    doc.end();
  });
}
